import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { WEB_EXCLUDED } from '../../src/extension/plugins.ts';
import { USERSCRIPT_EXCLUDED } from '../../src/userscript/plugins.ts';
import { PLUGINS, ROOT } from './paths.ts';
import { discoverPlugins } from './plugin.ts';

export const README = path.join(ROOT, 'README.md');
export const PLUGIN_NAMES = path.join(PLUGINS, 'names.generated.ts');
const BEGIN = '<!-- begin plugins -->';
const END = '<!-- end plugins -->';

export function pluginNamesModule(names = discoverPlugins().map((entry) => entry.name)): string {
  return [
    '// Generated by `bun run readme`. Do not edit.',
    'export const PLUGINS = [',
    ...names.map((name) => `  '${name}',`),
    '] as const;',
    '',
  ].join('\n');
}

function markdownTable(header: string[], rows: string[][], center: boolean[]): string {
  const widths = header.map((cell, i) => Math.max(3, cell.length, ...rows.map((row) => row[i].length)));
  const pad = (cell: string, i: number) => {
    const space = widths[i] - cell.length;
    const left = center[i] ? Math.floor(space / 2) : 0;
    return ' '.repeat(left) + cell + ' '.repeat(space - left);
  };
  const line = (cells: string[]) => `| ${cells.map(pad).join(' | ')} |`;
  const rule = widths.map((width, i) => (center[i] ? `:${'-'.repeat(width - 2)}:` : '-'.repeat(width)));
  return [line(header), `| ${rule.join(' | ')} |`, ...rows.map(line)].join('\n');
}

export async function pluginTable(): Promise<string> {
  const mark = (yes: boolean) => (yes ? '✓' : '—');
  const text = (value: string) => value.replaceAll('|', '\\|');
  const rows = await Promise.all(
    discoverPlugins().map(async ({ name, dir }) => {
      const meta = await import(pathToFileURL(path.join(dir, 'meta.ts')).href);
      const web = !(WEB_EXCLUDED as readonly string[]).includes(name);
      return [
        text(meta.pluginName),
        text(meta.description),
        mark(true),
        mark(web),
        mark(web && !USERSCRIPT_EXCLUDED.includes(name)),
      ];
    }),
  );
  return markdownTable(['Plugin', 'Description', 'Desktop', 'Extension', 'Userscript'], rows, [
    false,
    false,
    true,
    true,
    true,
  ]);
}

export function withPluginTable(readme: string, table: string): string {
  const start = readme.indexOf(BEGIN);
  const end = readme.indexOf(END);
  if (start < 0 || end < start) throw new Error(`README.md needs ${BEGIN} and ${END}`);
  return `${readme.slice(0, start + BEGIN.length)}\n\n${table}\n\n${readme.slice(end)}`;
}
